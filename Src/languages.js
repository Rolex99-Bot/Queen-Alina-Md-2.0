// ═══════ LANGUAGE HELPER ═══════
export function getString(key, lang = 'en') {
    const selectedLang = languages[lang] || languages.en;
    return selectedLang[key] || languages.en[key] || key;
}

// ═══════ DETECT LANGUAGE ═══════
export function detectLanguage(text) {
    // Simple detection based on Sinhala Unicode range
    const sinhalaRegex = /[\u0D80-\u0DFF]/;
    if (sinhalaRegex.test(text)) return 'si';
    return 'en';
}

// ═══════ GET USER LANGUAGE ═══════
export async function getUserLanguage(userId, database) {
    try {
        const user = await database.getUser(userId);
        return user?.language || 'en';
    } catch {
        return 'en';
    }
}

// ═══════ SET USER LANGUAGE ═══════
export async function setUserLanguage(userId, language, database) {
    try {
        await database.saveUser(userId, { language });
        return true;
    } catch {
        return false;
    }
}

export default languages;
